#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define LINE_CAPACITY 1024

typedef struct ListNode {
    char *text_data;            // Указатель на массив символов строки в динамической памяти (куче)
    struct ListNode *next_node; // Адрес следующего звена в цепочке (или NULL, если это конец)
} ListNode;

int main(void)
{
    // Статический буфер на стеке для приема сырого ввода пользователя
    char input_buf[LINE_CAPACITY];

    // Указатели на начало (голову) и конец (хвост) нашего списка
    ListNode *first = NULL;
    ListNode *last = NULL;

    // Считываем строки построчно из стандартного потока ввода (клавиатуры)
    // fgets безопасен, так как никогда не считает больше указанного размера буфера
    while (fgets(input_buf, sizeof(input_buf), stdin) != NULL) {

        // Проверяем первый символ введенной строки.
        // Если пользователь ввел точку (.), прерываем цикл ввода согласно заданию
        if (input_buf[0] == '.') {
            break;
        }

        // Вычисляем длину считанной строки (без учета завершающего нулевого байта '\0')
        size_t str_len = strlen(input_buf);

        // 1. Выделяем блок памяти в куче под сам узел списка (хранит указатели)
        ListNode *new_elem = malloc(sizeof(ListNode));
        if (!new_elem) {
            perror("Ошибка: не удалось выделить память под узел списка");
            return 1;
        }

        // 2. Выделяем блок памяти под символы строки.
        // Добавляем +1 байт обязательно для хранения скрытого терминатора строки '\0'
        new_elem->text_data = malloc(str_len + 1);
        if (!new_elem->text_data) {
            perror("Ошибка: не удалось выделить память под текст строки");
            free(new_elem); // Освобождаем ранее созданный узел, чтобы не было утечки
            return 1;
        }

        // Копируем символы из временного буфера в выделенную постоянную память
        strcpy(new_elem->text_data, input_buf);

        // Так как узел будет последним в цепочке, следующий за ним пока отсутствует
        new_elem->next_node = NULL;

        // Вставка нового узла в список:
        if (first == NULL) {
            // Если список был пуст, новый узел становится одновременно и началом, и хвостом
            first = new_elem;
            last = new_elem;
        } else {
            // Если в списке уже были элементы, привязываем новый узел к текущему хвосту
            last->next_node = new_elem;
            // И обновляем указатель хвоста — теперь последним стал новый узел
            last = new_elem;
        }
    }

    printf("\nСодержимое сохраненного списка:\n");

    // Итератор (указатель-бегунок) для последовательного прохода по списку
    ListNode *cursor = first;

    // Проходим от первого элемента до последнего (пока не встретим NULL)
    while (cursor != NULL) {
        // Выводим строку на экран. 
        // Символ переноса '\n' уже сохранен внутри text_data благодаря fgets
        printf("%s", cursor->text_data);

        // Передвигаем бегунок к следующему элементу
        cursor = cursor->next_node;
    }

    // Полное освобождение динамической памяти (профилактика утечек памяти)
    cursor = first;

    while (cursor != NULL) {
        // Сохраняем адрес следующего элемента до того, как удалим текущий
        ListNode *step_ahead = cursor->next_node;

        // Память освобождается строго в порядке, обратном выделению:
        free(cursor->text_data); // 1. Сначала удаляем массив символов
        free(cursor);            // 2. Затем удаляем сам узел-контейнер

        // Переходим к сохраненному следующему узлу
        cursor = step_ahead;
    }

    return 0;
}